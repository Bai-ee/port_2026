// Pure computation of every generated production artefact (no fs, no env).
// scripts/theme/build-theme.mjs writes these strings; check-theme.mjs and
// generated-drift.test.js compare them against the checked-in files.

import { parseDefinition } from '../validate.js';
import { exportThemeJson } from '../export.js';
import { resolveBoth } from '../resolve.js';
import { toCss } from '../css.js';
import { buildReport } from '../report.js';
import { BASELINE_DEFINITION } from '../baseline.js';
import { getBootstrapScript } from '../bootstrap-source.js';

const json = (v) => `${JSON.stringify(v, null, 2)}\n`;

/** Slim, runtime-sized view: tokens + scene only (the main bundle must stay small). */
function slim(resolved) {
  return { mode: resolved.mode, meta: resolved.meta, tokens: resolved.tokens, scene: resolved.scene };
}

/**
 * @param jsonText  contents of production-theme.json
 * @returns { ok, errors, warnings, definition?, files? }
 *   files: { css, resolved, runtime, canonicalJson, baselineReport }
 */
export function buildProductionOutputs(jsonText) {
  const parsed = parseDefinition(jsonText);
  if (!parsed.ok) return { ok: false, errors: parsed.errors, warnings: parsed.warnings };
  const def = parsed.definition;
  const pair = resolveBoth(def, { assumeCanonical: true });
  const head = {
    version: pair.light.version,
    definitionId: pair.light.definitionId,
    hash: pair.light.hash,
    defaults: pair.light.defaults,
    features: pair.light.features,
  };
  const runtime = { ...head, light: slim(pair.light), dark: slim(pair.dark) };
  return {
    ok: true,
    errors: [],
    warnings: parsed.warnings,
    definition: def,
    files: {
      css: toCss(pair),
      resolved: json({ ...head, light: pair.light, dark: pair.dark }),
      runtime: json(runtime),
      // same data as an ES module: no JSON import attributes needed (Node tests, bundlers)
      runtimeModule: `// GENERATED by scripts/theme/build-theme.mjs from production-theme.json. DO NOT EDIT.\nexport default ${JSON.stringify(runtime, null, 2)};\n`,
      canonicalJson: exportThemeJson(def),
      baselineReport: json(buildReport(BASELINE_DEFINITION)),
      bootstrap: getBootstrapScript({ defaultPreference: def.defaults.viewerPreference }),
    },
  };
}
