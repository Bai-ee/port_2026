// toCss: deterministic CSS for a theme (contract §5). Byte-stable: fixed
// ordering, no timestamps. `!important` appears exactly once (transition
// suppression while dragging / switching).

import { TOKEN_NAMES } from './tokens.js';
import { resolveBoth } from './resolve.js';

const DEFAULT_SELECTORS = Object.freeze({
  light: ':root[data-theme="light"], [data-theme-scope="light"]',
  dark: ':root[data-theme="dark"], [data-theme-scope="dark"]',
  lightScope: '[data-theme-scope="light"]',
  darkScope: '[data-theme-scope="dark"]',
});

function isResolvedPair(x) {
  return !!(x && x.light && x.dark && x.light.tokens && x.dark.tokens);
}

function decls(resolved, indent) {
  const pad = ' '.repeat(indent);
  const lines = [`${pad}color-scheme: ${resolved.mode};`];
  for (const name of TOKEN_NAMES) lines.push(`${pad}${name}: ${resolved.tokens[name]};`);
  return lines.join('\n');
}

function block(selector, resolved, indent = 0) {
  const pad = ' '.repeat(indent);
  return `${pad}${selector} {\n${decls(resolved, indent + 2)}\n${pad}}`;
}

/**
 * @param input    a theme definition, or a resolved pair { light, dark } from resolveBoth
 * @param options  { noJsFallback=true, selectors?, scopeOnly=false, header=true }
 */
export function toCss(input, options = {}) {
  const { noJsFallback = true, selectors = {}, scopeOnly = false, header = true } = options;
  const pair = isResolvedPair(input) ? input : resolveBoth(input);
  const { light, dark } = pair;
  const pref = light.defaults ? light.defaults.viewerPreference : 'light';
  const features = light.features || { focusRing: false, selection: false };
  const out = [];

  if (header) {
    out.push(`/* theme: ${light.definitionId} hash:${light.hash} — GENERATED by lib/theme (scripts/theme/build-theme.mjs). DO NOT EDIT. */`);
  }

  if (scopeOnly) {
    out.push(block(selectors.lightScope || DEFAULT_SELECTORS.lightScope, light));
    out.push(block(selectors.darkScope || DEFAULT_SELECTORS.darkScope, dark));
    return `${out.join('\n')}\n`;
  }

  if (noJsFallback) {
    const base = pref === 'dark' ? dark : light;
    out.push(block(selectors.fallback || ':root', base));
  }
  out.push(block(selectors.light || DEFAULT_SELECTORS.light, light));
  out.push(block(selectors.dark || DEFAULT_SELECTORS.dark, dark));

  if (noJsFallback && pref === 'system') {
    out.push(`@media (prefers-color-scheme: dark) {\n  :root:not([data-theme]) {\n${decls(dark, 4)}\n  }\n}`);
  }

  out.push(
    ':root[data-theme-switching], :root[data-theme-switching] *, :root[data-theme-switching] *::before, :root[data-theme-switching] *::after { transition: none !important; }'
  );
  if (features.selection) {
    out.push(':root[data-theme] ::selection, [data-theme-scope] ::selection { background: var(--t-selection-bg); color: var(--t-selection-fg); }');
  }
  if (features.focusRing) {
    out.push(':where(:focus-visible) { outline: 2px solid var(--t-focus); outline-offset: 2px; }');
  }
  return `${out.join('\n')}\n`;
}
