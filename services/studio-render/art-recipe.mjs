function clamp(value, [min, max]) {
  return Math.min(max, Math.max(min, value));
}

function clampFields(obj, bounds) {
  const out = { ...obj };
  Object.entries(bounds).forEach(([key, range]) => {
    if (isFiniteNum(out[key])) out[key] = clamp(out[key], range);
  });
  return out;
}

