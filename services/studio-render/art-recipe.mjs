// Shape rules for the pinned screen-still reference (Slice F2) — MIRRORS
// api/_lib/studio-screen-stills.cjs's sanitizeScreenStillRef exactly (that
// module re-validates at its own Storage boundary; this recipe boundary
// can't import the CJS module without dragging firebase-admin into the
// pure-ESM recipe graph, so the small rule set is duplicated with a drift
// note on both sides). sha256 is canonical lowercase hex only.
const SCREEN_STILL_EXTS = ['png', 'jpg', 'webp'];
const SCREEN_STILL_DIMENSION_RANGE = [16, 8192];
const SCREEN_STILL_MAX_BYTES = 8 * 1024 * 1024;
const SCREEN_STILL_MAX_PIXELS = 32 * 1024 * 1024; // mirrors the lib's MAX_TOTAL_PIXELS decoded-pixel budget
function sanitizeScreenStillShape(raw) {
  if (!isPlainObject(raw)) return null;
  const okDim = (v) => Number.isInteger(v) && v >= SCREEN_STILL_DIMENSION_RANGE[0] && v <= SCREEN_STILL_DIMENSION_RANGE[1];
  if (typeof raw.sha256 !== 'string' || !/^[0-9a-f]{64}$/.test(raw.sha256)) return null;
  if (!SCREEN_STILL_EXTS.includes(raw.ext)) return null;
  if (!okDim(raw.width) || !okDim(raw.height)) return null;
  if (raw.width * raw.height > SCREEN_STILL_MAX_PIXELS) return null;
  if (!Number.isInteger(raw.bytes) || raw.bytes <= 0 || raw.bytes > SCREEN_STILL_MAX_BYTES) return null;
  return { sha256: raw.sha256, ext: raw.ext, width: raw.width, height: raw.height, bytes: raw.bytes };
}

