// function with a non-empty "on" set is always rejected before a job is
// ever created (see app/api/dashboard/proof-render/route.js), so no
// unvalidated field value from `raw` is ever persisted. A future slice that
// implements real hero-text rendering must replace this with the real
// sanitizer (vendored, same pattern as scene-recipe.js) instead of building
// on this stub.
const MAX_TEXT_LAYERS_RECIPE = 3; // mirrors text-layers.js's MAX_TEXT_LAYERS
function detectTextLayers(raw) {
  if (!Array.isArray(raw)) return [];
  return raw.slice(0, MAX_TEXT_LAYERS_RECIPE)
    .filter(isPlainObject)
    .map((layer) => ({ on: layer.on !== false }));
}

/**
 * Sanitize the Scene Lab's per-scene tweak overrides (Slice B/C — Codex
 * constraint: "normalize and sanitize sceneTweaks; don't silently omit
 * them"). Field-PRESENCE is semantic (composeSceneDef distinguishes absent
 * from set — an absent field keeps the preset value, `pano: ''` REMOVES the
 * preset's plate), so this returns ONLY the keys that survive validation —
 * never fills defaults, never carries an unknown key or invalid value
 * (which would otherwise let a raw payload smuggle an arbitrary pano path
 * into asset resolution; pano/groundTex are strict allowlist-or-empty).
 */
function sanitizeSceneTweaks(raw) {
  if (!isPlainObject(raw)) return {};
  const out = {};
  Object.entries(SCENE_TWEAK_BOUNDS).forEach(([key, range]) => {
    if (isFiniteNum(raw[key])) out[key] = clamp(raw[key], range);
  });
  if (isBool(raw.fogOn)) out.fogOn = raw.fogOn;
  ['fogColor', 'ground', 'groundTint'].forEach((key) => {
    if (isHexColor(raw[key])) out[key] = raw[key];
  });
  if (raw.pano === '' || (typeof raw.pano === 'string' && SCENE_PANO_IDS.has(raw.pano))) out.pano = raw.pano;
  if (raw.groundTex === '' || (typeof raw.groundTex === 'string' && GROUND_TEXTURE_IDS.has(raw.groundTex))) out.groundTex = raw.groundTex;
  return out;
}

