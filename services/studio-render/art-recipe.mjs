function isPlainObject(v) {
  return Boolean(v) && typeof v === 'object' && !Array.isArray(v);
}

// Recursively freezes every object/array reachable from `value` — the
// top-level result, `recipe`, every nested field object (mat/phys/anim/cam/
// glass/shotCam/diffusionCamera/fx), `lightCans` and each can, `extraInstances`
// and every instance's own nested transform/material/motion/appearance/
// formatOverrides/random objects, `support`, and `warnings` (the array and
// each entry object). Only ever called on freshly-constructed output objects
// (never on `raw`/`payload` — every field above is built via spread/map/
// dedicated normalize functions that already return new objects, so this
// never reaches back into, or freezes, anything the caller passed in).
function deepFreeze(value) {
  if (value === null || typeof value !== 'object' || Object.isFrozen(value)) return value;
  Object.freeze(value);
  Object.values(value).forEach(deepFreeze);
  return value;
}

function pickEnum(value, allowlist, fallback) {
  return allowlist.includes(value) ? value : fallback;
}

// Capability-DETECTION only, not a real sanitizer — deliberately does not
// import/duplicate app/dashboard/studio/text-layers.js's full
// sanitizeTextLayers (fontId/color/anim/backdrop/etc.), because nothing in
// this render pass draws text yet (art-scene.mjs has no text-canvas/overlay
// compositing at all). checkCapabilities' 'textLayers' entry only needs to
