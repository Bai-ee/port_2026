#!/usr/bin/env node
// vendor-elements.mjs — Slice 4a packaging fix. Copies the EXACT, closed
// dependency closure `art-recipe.mjs` needs from `app/dashboard/studio/
// elements/` into `services/studio-render/vendor/elements/`, so the files
// are service-local (tracked in git, present on disk regardless of how the
// container gets built) instead of reaching outside this service's own
// directory.
//
// WHY this exists: `deploy-cloud-run.sh` builds from `services/studio-render`
// only (`--source .`, run after `cd`ing into this directory — see that
// script's own header comment about why: a repo-root deploy previously
// shipped `next start` to this service by mistake), and the Dockerfile COPYs
// an explicit, closed file list (never `COPY . .`) — so anything
// `art-recipe.mjs` imports via a path that reaches OUTSIDE this directory
// (e.g. `../../app/dashboard/studio/elements/...`) can never resolve inside
// the real built image. Vendoring is the fix: make the dependency closure
// service-local, so the existing explicit-COPY-list Dockerfile pattern
// (never broadened to `COPY . .`) can include it with two precise lines.
//
// This is the SAME "committed mirror of a real source, regenerated by an
// explicit sync step" pattern this repo already uses for `ds-bundle/`
// (CLAUDE.md: "published design system... mirrors the real source",
// generator `.design-sync/`) — not a new architectural idea.
//
// Vendored files ARE committed to git (reviewable, and the Docker/Cloud
// Build context needs them present on disk regardless of who invokes the
// build). `__tests__/art-recipe.test.mjs`'s "vendor is in sync" tests do a
// byte-for-byte comparison against the real source on every test run — if
// someone edits `elements/scene-recipe.js` (etc.) without re-running this
// script, that test fails immediately instead of silently shipping stale
// logic. `deploy-cloud-run.sh` also re-runs this script right before
// deploying, as a belt-and-suspenders freshness guarantee independent of
// whether a developer remembered to run it and commit the result.
//
// Deliberately an EXPLICIT file list, not a whole-directory copy — so a
// future addition to elements/ doesn't silently expand what gets vendored
// (and shipped into the render service's Docker image) without a deliberate
// edit to this list.

import { existsSync, mkdirSync, copyFileSync, readdirSync, rmSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SERVICE_DIR = path.resolve(__dirname, '..');
const SOURCE_DIR = path.resolve(SERVICE_DIR, '../../app/dashboard/studio/elements');
const TARGET_DIR = path.resolve(SERVICE_DIR, 'vendor/elements');

// art-recipe.mjs's full, closed dependency closure (verified by direct
// inspection: scene-recipe.js, randomize.js, catalog.js, validators.js,
// intensity.js have zero imports of their own; schema.js imports catalog.js
// + validators.js; placement.js imports catalog.js; scene-elements.js
// imports catalog.js + schema.js + randomize.js + placement.js + intensity.js.
// Nothing here imports three.js, `window`, or `document`.
export const VENDORED_FILES = [
  'scene-recipe.js',
  'scene-elements.js',
  'schema.js',
  'validators.js',
  'catalog.js',
  'placement.js',
  'quality.js',
  'intensity.js',
  'randomize.js',
  // Slice E (server T-shirt parity) — the primary-tshirt closure, imported
  // DIRECTLY by art-scene.mjs's generated page (true reuse, not a port):
  // factories.js ('hanging-tshirt' factory: topology/panel materials/grain/
  // print shader/hanger/sim mapping), its remaining import closure
  // (particle-math.js, glb-loader.js — tshirt-mesh.js is the garment
  // mesh+sim itself), and primary-cloth.js (mat/phys/anim/tshirtPrint →
  // instance mapping).
  'factories.js',
  'tshirt-mesh.js',
  'primary-cloth.js',
  'particle-math.js',
  'glb-loader.js',
  // Capture Frame parity (Final Render frame/crop round) — pure resolution/
  // crop math (computeCropSourceResolution etc.); zero imports, DOM-free.
  'video-export.js',
];

/**
 * `targetDir` defaults to the canonical `services/studio-render/vendor/
 * elements/` (production behavior, and `deploy-cloud-run.sh`'s own
 * no-args call, both unchanged) — but accepts an explicit override so a
 * test can vendor into an ISOLATED temp directory instead (Codex re-review:
 * `npm test` runs test files concurrently; the idempotency test previously
 * called this against the CANONICAL directory, deleting and recreating it
 * while OTHER test files were concurrently importing modules from inside
 * it — a real, observed test-isolation race, not a hypothetical one).
 */
export function vendorElements({ log = () => {}, targetDir = TARGET_DIR } = {}) {
  rmSync(targetDir, { recursive: true, force: true });
  mkdirSync(targetDir, { recursive: true });
  for (const file of VENDORED_FILES) {
    const from = path.join(SOURCE_DIR, file);
    const to = path.join(targetDir, file);
    if (!existsSync(from)) throw new Error(`vendor-elements: source file missing: ${from}`);
    copyFileSync(from, to);
    log(`vendored ${file}`);
  }
  const extra = readdirSync(targetDir).filter((f) => !VENDORED_FILES.includes(f));
  if (extra.length) throw new Error(`vendor-elements: unexpected leftover file(s) in ${targetDir}: ${extra.join(', ')}`);
  return { sourceDir: SOURCE_DIR, targetDir, files: VENDORED_FILES };
}

// Run directly (`node scripts/vendor-elements.mjs`) as well as importable
// (tests import `vendorElements`/`VENDORED_FILES` to re-run and verify sync).
if (import.meta.url === `file://${process.argv[1]}`) {
  const result = vendorElements({ log: (msg) => console.log(msg) });
  console.log(`Vendored ${result.files.length} file(s) from ${result.sourceDir} into ${result.targetDir}`);
}
