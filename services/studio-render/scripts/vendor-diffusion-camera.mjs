#!/usr/bin/env node
// vendor-diffusion-camera.mjs — Phase B (STUDIO-DETERMINISTIC-FINAL-RENDER-
// SONNET-HANDOFF.md, "Interrupted export recovery: Phase B — Diffusion
// Camera server parity"). Vendors the TWO pieces of client logic the server
// composer chain must reuse verbatim rather than re-author:
//
//   1. `diffusion-focus.js` (app/dashboard/studio/diffusion-focus.js) — a
//      standalone, zero-import, pure ESM module (focal-target resolution +
//      CoC/blur math). Byte-copied, same discipline as vendor-elements.mjs
//      (this file just isn't UNDER elements/, so it can't ride that script's
//      fixed SOURCE_DIR).
//   2. `DIFFUSION_SHADER`/`TREATMENT_SHADER` (ClothStudio.jsx module-scope
//      consts) — extracted via the SAME depth-counted-literal-slice + `vm`
//      sandbox-eval technique vendor-scene-presets.mjs already established
//      (reused directly, not reimplemented: `extractConstObject` is
//      imported from that script). The naive brace counter works here even
//      though the shader strings themselves are full of GLSL `{`/`}` —
//      verified directly (see __tests__/diffusion-camera-vendor.test.mjs):
//      GLSL is itself brace-balanced, so scanning through the string
//      content nets zero depth change and the true object boundary is still
//      found correctly.
//
// WHY vendor extraction (not a ClothStudio.jsx import) — the "zero client
// edits" option this phase's handoff explicitly offered, chosen over the
// Slice E "true reuse via page import" pattern specifically because these
// two shader objects live INSIDE the ClothStudio.jsx component file (like
// SCENE_PRESETS), not in an importable elements/ module, and re-exporting
// them from ClothStudio.jsx would touch the client bundle for a purely
// server-side feature. Same committed-mirror + drift-test discipline as
// every other vendored file in this service: the generated/copied output is
// committed, and __tests__/diffusion-camera-vendor.test.mjs re-derives both
// from the real sources on every test run.

import { readFileSync, writeFileSync, copyFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { extractConstObject } from './vendor-scene-presets.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SERVICE_DIR = path.resolve(__dirname, '..');
const CLOTHSTUDIO_SOURCE = path.resolve(SERVICE_DIR, '../../app/dashboard/studio/ClothStudio.jsx');
const DIFFUSION_FOCUS_SOURCE = path.resolve(SERVICE_DIR, '../../app/dashboard/studio/diffusion-focus.js');

export const DIFFUSION_FOCUS_TARGET = path.resolve(SERVICE_DIR, 'vendor/diffusion-focus.js');
export const DIFFUSION_SHADERS_TARGET = path.resolve(SERVICE_DIR, 'vendor/diffusion-shaders.mjs');

export function generateDiffusionShadersModule(clothStudioSource) {
  const diffusionShader = extractConstObject(clothStudioSource, 'DIFFUSION_SHADER');
  const treatmentShader = extractConstObject(clothStudioSource, 'TREATMENT_SHADER');
  return `// GENERATED by scripts/vendor-diffusion-camera.mjs — do not hand-edit.
// Source of truth: app/dashboard/studio/ClothStudio.jsx (DIFFUSION_SHADER /
// TREATMENT_SHADER — the live two-pass diffusion/treatment finishing
// chain). Re-run the script after editing them there;
// __tests__/diffusion-camera-vendor.test.mjs fails on drift. Consumed
// Node-side only (services/studio-render/art-scene.mjs imports these and
// embeds them as JSON literals into the generated render page — the exact
// same "vendor + embed as JSON" pattern art-scene.mjs already uses for
// RECIPE/EFFECTIVE_SCENE), never copied into a render workDir as its own
// browser-loaded file.
export const DIFFUSION_SHADER = ${JSON.stringify(diffusionShader, null, 2)};

export const TREATMENT_SHADER = ${JSON.stringify(treatmentShader, null, 2)};
`;
}

/**
 * Runs both vendoring steps. `log` defaults to a no-op (tests can call this
 * silently); the CLI invocation below passes console.log.
 */
export function vendorDiffusionCamera({ log = () => {} } = {}) {
  if (!existsSync(DIFFUSION_FOCUS_SOURCE)) {
    throw new Error(`vendor-diffusion-camera: source file missing: ${DIFFUSION_FOCUS_SOURCE}`);
  }
  copyFileSync(DIFFUSION_FOCUS_SOURCE, DIFFUSION_FOCUS_TARGET);
  log(`vendored diffusion-focus.js -> ${DIFFUSION_FOCUS_TARGET}`);

  const clothStudioSource = readFileSync(CLOTHSTUDIO_SOURCE, 'utf8');
  writeFileSync(DIFFUSION_SHADERS_TARGET, generateDiffusionShadersModule(clothStudioSource));
  log(`vendored DIFFUSION_SHADER/TREATMENT_SHADER -> ${DIFFUSION_SHADERS_TARGET}`);

  return { diffusionFocusTarget: DIFFUSION_FOCUS_TARGET, diffusionShadersTarget: DIFFUSION_SHADERS_TARGET };
}

const isMainModule = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMainModule) {
  vendorDiffusionCamera({ log: (msg) => console.log(msg) });
}
