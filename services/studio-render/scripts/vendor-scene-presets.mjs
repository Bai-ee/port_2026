#!/usr/bin/env node
// vendor-scene-presets.mjs — Phase 5 scene/background parity (Slice B/C).
// Extracts the THREE scene-background constant tables from ClothStudio.jsx
// — SCENE_PRESETS (79 sets), GROUND_TEXTURES (7 surfaces), PANO_PLATES (16
// plates) — and writes them as a generated, importable pure-data module at
// services/studio-render/vendor/scene-presets.mjs.
//
// WHY extraction instead of imports: these tables live INSIDE the
// ClothStudio.jsx component file (not an importable elements/ module), so
// the vendor-elements.mjs byte-copy pattern can't reach them. Same
// committed-mirror + drift-test discipline though: the generated module is
// committed, art-recipe.test.mjs's enum-parity extractor already guards the
// SCENE_PRESETS key set, and __tests__/scene-presets-vendor.test.mjs
// re-extracts all three tables from ClothStudio.jsx on every test run and
// deep-equals them against this generated module — an un-regenerated edit
// fails immediately instead of silently shipping stale scene definitions.
//
// Extraction = depth-counted literal slice + a bare `vm` sandbox eval of
// exactly that object literal (no imports, no function calls — the tables
// are plain string/number/array data by construction; anything else would
// throw here at generation time, never at render time).

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import vm from 'node:vm';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SOURCE = path.resolve(__dirname, '../../../app/dashboard/studio/ClothStudio.jsx');
const TARGET = path.resolve(__dirname, '../vendor/scene-presets.mjs');

export function extractConstObject(source, constName, opener = '{', closer = '}') {
  const marker = `const ${constName} = ${opener}`;
  const startIdx = source.indexOf(marker);
  if (startIdx === -1) throw new Error(`could not find "${marker}" in ClothStudio.jsx`);
  const literalStart = startIdx + `const ${constName} = `.length;
  let depth = 0;
  let end = -1;
  for (let i = literalStart; i < source.length; i += 1) {
    const ch = source[i];
    if (ch === opener) depth += 1;
    else if (ch === closer) {
      depth -= 1;
      if (depth === 0) { end = i + 1; break; }
    }
  }
  if (end === -1) throw new Error(`unbalanced literal for ${constName}`);
  const literal = source.slice(literalStart, end);
  // Bare sandbox: the tables are plain data literals. Anything that would
  // need scope (identifiers, calls, template strings referencing vars)
  // throws right here — at generation time, loudly.
  return vm.runInNewContext(`(${literal})`, Object.create(null), { timeout: 1000 });
}

export function generateSceneVendorModule(source) {
  const scenePresets = extractConstObject(source, 'SCENE_PRESETS');
  const groundTextures = extractConstObject(source, 'GROUND_TEXTURES');
  const panoPlates = extractConstObject(source, 'PANO_PLATES', '[', ']');
  const framePresets = extractConstObject(source, 'FRAME_PRESETS');
  return `// GENERATED by scripts/vendor-scene-presets.mjs — do not hand-edit.
// Source of truth: app/dashboard/studio/ClothStudio.jsx (SCENE_PRESETS /
// GROUND_TEXTURES / PANO_PLATES / FRAME_PRESETS). Re-run the script after
// editing them there; __tests__/scene-presets-vendor.test.mjs fails on drift.
export const SCENE_PRESETS = ${JSON.stringify(scenePresets, null, 2)};

export const GROUND_TEXTURES = ${JSON.stringify(groundTextures, null, 2)};

export const PANO_PLATES = ${JSON.stringify(panoPlates, null, 2)};

export const FRAME_PRESETS = ${JSON.stringify(framePresets, null, 2)};
`;
}

const isMainModule = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMainModule) {
  const source = readFileSync(SOURCE, 'utf8');
  writeFileSync(TARGET, generateSceneVendorModule(source));
  console.log(`Vendored SCENE_PRESETS/GROUND_TEXTURES/PANO_PLATES into ${TARGET}`);
}
